export type Widen<T> = T extends string
	? string
	: T extends (...args: infer A) => infer R
		? (...args: A) => Widen<R>
		: T extends readonly (infer E)[]
			? readonly Widen<E>[]
			: T extends object
				? { readonly [K in keyof T]: Widen<T[K]> }
				: T;

export type TranslationDict = Widen<typeof en>;
